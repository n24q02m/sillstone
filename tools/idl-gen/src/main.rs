//! Code generator for Sillstone ABI and multi-language SDKs.
//!
//! Translates `abi/sillstone.idl` into C headers, Rust FFI glue, and bindings
//! for Python, Node.js (N-API), Go (cgo), and Java (JNI).

use std::env;
use std::fs;
use std::path::PathBuf;

#[derive(Debug, Clone)]
struct Arg {
    name: String,
    ty: String,
}

#[derive(Debug, Clone)]
struct Function {
    name: String,
    args: Vec<Arg>,
    ret: String,
}

fn parse_idl(content: &str) -> Vec<Function> {
    let mut fns = Vec::new();
    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        if let Some(rest) = trimmed.strip_prefix("fn ") {
            let parts: Vec<&str> = rest.split(" -> ").collect();
            let sig = parts[0].trim();
            let ret = if parts.len() > 1 {
                parts[1].trim().to_string()
            } else {
                "void".to_string()
            };

            let open = sig.find('(').expect("missing ( in signature");
            let close = sig.find(')').expect("missing ) in signature");
            let name = sig[..open].trim().to_string();
            let args_str = sig[open + 1..close].trim();

            let mut args = Vec::new();
            if !args_str.is_empty() {
                for arg_part in args_str.split(',') {
                    let kv: Vec<&str> = arg_part.split(':').collect();
                    args.push(Arg {
                        name: kv[0].trim().to_string(),
                        ty: kv[1].trim().to_string(),
                    });
                }
            }
            fns.push(Function { name, args, ret });
        }
    }
    fns
}

fn is_digest_fn(name: &str) -> bool {
    name.starts_with("sillstone_digest_")
}
fn is_math_dst_fn(name: &str) -> bool {
    name.starts_with("sillstone_math_dst")
}


fn digest_len(name: &str) -> usize {
    if name.ends_with("_512") {
        64
    } else {
        32
    }
}

fn gen_c_header(fns: &[Function]) -> String {
    let mut out = String::new();
    out.push_str("/* Generated by sillstone-idl-gen. DO NOT EDIT. */\n");
    out.push_str("#ifndef SILLSTONE_H\n#define SILLSTONE_H\n\n");
    out.push_str("#include <stdint.h>\n#include <stddef.h>\n\n");
    out.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");

    for f in fns {
        let c_ret = match f.ret.as_str() {
            "u32" => "uint32_t",
            "u64" => "uint64_t",
            "i32" => "int32_t",
            "usize" => "size_t",
            "void" => "void",
            _ => "void",
        };
        out.push_str(&format!("{c_ret} {}(", f.name));
        if f.args.is_empty() {
            out.push_str("void");
        } else {
            let arg_strs: Vec<String> = f
                .args
                .iter()
                .map(|a| {
                    let c_ty = match a.ty.as_str() {
                        "*const u8" => "const uint8_t *",
                        "*mut u8" => "uint8_t *",
                        "*const f64" => "const double *",
                        "*mut f64" => "double *",
                        "f64" => "double",
                        "usize" => "size_t",
                        "u32" => "uint32_t",
                        "u64" => "uint64_t",
                        "i32" => "int32_t",
                        _ => "void *",
                    };
                    let sep = if c_ty.ends_with('*') { "" } else { " " };
                    format!("{c_ty}{sep}{}", a.name)
                })
                .collect();
            out.push_str(&arg_strs.join(", "));
        }
        out.push_str(");\n\n");
    }

    out.push_str("#ifdef __cplusplus\n}\n#endif\n\n#endif /* SILLSTONE_H */\n");
    out
}

fn gen_python(fns: &[Function]) -> String {
    let mut out = String::new();
    out.push_str("# Generated by sillstone-idl-gen. DO NOT EDIT.\n");
    out.push_str("import ctypes\nimport os\nimport sys\n\n");
    out.push_str("def _load_lib():\n");
    out.push_str("    ext = '.dll' if sys.platform == 'win32' else ('.dylib' if sys.platform == 'darwin' else '.so')\n");
    out.push_str("    prefix = '' if sys.platform == 'win32' else 'lib'\n");
    out.push_str("    lib_name = f'{prefix}sillstone_ffi{ext}'\n");
    out.push_str("    dir_path = os.path.dirname(os.path.abspath(__file__))\n");
    out.push_str("    candidates = [\n");
    out.push_str("        os.path.join(dir_path, lib_name),\n");
    out.push_str("        os.path.join(dir_path, '..', '..', '..', 'target', 'release', lib_name),\n");
    out.push_str("        os.path.join(dir_path, '..', '..', '..', 'target', 'debug', lib_name),\n");
    out.push_str("    ]\n");
    out.push_str("    for c in candidates:\n");
    out.push_str("        if os.path.exists(c):\n");
    out.push_str("            return ctypes.CDLL(c)\n");
    out.push_str("    return None\n\n");
    out.push_str("LIB = _load_lib()\n\n");

    for f in fns {
        out.push_str(&format!("def {}_raw(*args):\n", f.name));
        out.push_str("    if LIB is None:\n        raise RuntimeError('sillstone_ffi library not loaded')\n");
        out.push_str(&format!("    fn = getattr(LIB, '{}')\n", f.name));
        let py_ret = match f.ret.as_str() {
            "u32" => "ctypes.c_uint32",
            "u64" => "ctypes.c_uint64",
            "i32" => "ctypes.c_int32",
            "usize" => "ctypes.c_size_t",
            _ => "None",
        };
        out.push_str(&format!("    fn.restype = {py_ret}\n"));
        let py_args: Vec<&str> = f
            .args
            .iter()
            .map(|a| match a.ty.as_str() {
                "*const u8" => "ctypes.c_char_p",
                "*mut u8" => "ctypes.c_char_p",
                "*const f64" => "ctypes.POINTER(ctypes.c_double)",
                "*mut f64" => "ctypes.POINTER(ctypes.c_double)",
                "f64" => "ctypes.c_double",
                "usize" => "ctypes.c_size_t",
                "u32" => "ctypes.c_uint32",
                "u64" => "ctypes.c_uint64",
                "i32" => "ctypes.c_int32",
                _ => "ctypes.c_void_p",
            })
            .collect();
        out.push_str(&format!("    fn.argtypes = [{}]\n", py_args.join(", ")));
        out.push_str("    return fn(*args)\n\n");
    }

    out
}

fn gen_go(fns: &[Function]) -> String {
    let mut out = String::new();
    out.push_str("// Code generated by sillstone-idl-gen. DO NOT EDIT.\n");
    out.push_str("package sillstone\n\n");
    out.push_str("/*\n#cgo CFLAGS: -I../../../include\n#cgo LDFLAGS: -L../../../target/debug -L../../../target/release -lsillstone_ffi\n#cgo windows LDFLAGS: -lws2_32 -luserenv -lntdll -lbcrypt\n#include \"sillstone.h\"\n*/\nimport \"C\"\nimport \"unsafe\"\n\n");

    for f in fns {
        let go_name = f
            .name
            .split('_')
            .map(|part| {
                let mut c = part.chars();
                match c.next() {
                    None => String::new(),
                    Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
                }
            })
            .collect::<String>();

        if f.name == "sillstone_buffer_checksum" {
            out.push_str(&format!(
                "func {go_name}(data []byte) uint64 {{\n"
            ));
            out.push_str("    if len(data) == 0 {\n        return uint64(C.sillstone_buffer_checksum(nil, 0))\n    }\n");
            out.push_str("    return uint64(C.sillstone_buffer_checksum((*C.uint8_t)(unsafe.Pointer(&data[0])), C.size_t(len(data))))\n");
            out.push_str("}\n\n");
        } else if is_digest_fn(&f.name) {
            let out_len = digest_len(&f.name);
            out.push_str(&format!("func {go_name}(data []byte) []byte {{\n"));
            out.push_str(&format!("    out := make([]byte, {out_len})\n"));
            out.push_str("    var ptr *C.uint8_t\n");
            out.push_str("    if len(data) > 0 {\n        ptr = (*C.uint8_t)(unsafe.Pointer(&data[0]))\n    }\n");
            out.push_str(&format!(
                "    C.{}(ptr, C.size_t(len(data)), (*C.uint8_t)(unsafe.Pointer(&out[0])))\n",
                f.name
            ));
            out.push_str("    return out\n}\n\n");
        } else if is_math_dst_fn(&f.name) {
            out.push_str(&format!("func {go_name}(data []float64) []float64 {{\n"));
            out.push_str("    out := make([]float64, len(data))\n");
            out.push_str("    if len(data) == 0 {\n        return out\n    }\n");
            out.push_str(&format!(
                "    C.{}((*C.double)(unsafe.Pointer(&data[0])), C.size_t(len(data)), (*C.double)(unsafe.Pointer(&out[0])))\n",
                f.name
            ));
            out.push_str("    return out\n}\n\n");
        } else if f.args.is_empty() {
            let go_ret = match f.ret.as_str() {
                "u32" => "uint32",
                "u64" => "uint64",
                _ => "void",
            };
            out.push_str(&format!("func {go_name}() {go_ret} {{\n"));
            out.push_str(&format!("    return {go_ret}(C.{}())\n", f.name));
            out.push_str("}\n\n");
        }
    }
    out
}

fn gen_node_napi(fns: &[Function]) -> String {
    let mut out = String::new();
    out.push_str("/* Generated by sillstone-idl-gen. DO NOT EDIT. */\n");
    out.push_str("#include <node_api.h>\n#include <stdint.h>\n#include <stddef.h>\n#include \"sillstone.h\"\n\n");

    for f in fns {
        out.push_str(&format!("static napi_value n_{}(napi_env env, napi_callback_info info) {{\n", f.name));
        if f.name == "sillstone_buffer_checksum" {
            out.push_str("    size_t argc = 1;\n    napi_value args[1];\n");
            out.push_str("    napi_get_cb_info(env, info, &argc, args, NULL, NULL);\n");
            out.push_str("    void* data;\n    size_t length;\n");
            out.push_str("    napi_get_buffer_info(env, args[0], &data, &length);\n");
            out.push_str("    uint64_t res = sillstone_buffer_checksum((const uint8_t*)data, length);\n");
            out.push_str("    napi_value result;\n    napi_create_bigint_uint64(env, res, &result);\n    return result;\n");
        } else if is_digest_fn(&f.name) {
            let out_len = digest_len(&f.name);
            out.push_str("    size_t argc = 1;\n    napi_value args[1];\n");
            out.push_str("    napi_get_cb_info(env, info, &argc, args, NULL, NULL);\n");
            out.push_str("    void* data = NULL;\n    size_t length = 0;\n");
            out.push_str("    if (argc > 0) {\n        napi_get_buffer_info(env, args[0], &data, &length);\n    }\n");
            out.push_str(&format!("    uint8_t out[{out_len}];\n"));
            out.push_str(&format!("    {}((const uint8_t*)data, length, out);\n", f.name));
            out.push_str(&format!("    napi_value result;\n    napi_create_buffer_copy(env, {out_len}, out, NULL, &result);\n    return result;\n"));
        } else if is_math_dst_fn(&f.name) {
            out.push_str("    size_t argc = 1;\n    napi_value args[1];\n");
            out.push_str("    napi_get_cb_info(env, info, &argc, args, NULL, NULL);\n");
            out.push_str("    void* data = NULL;\n    size_t length = 0;\n");
            out.push_str("    if (argc > 0) {\n        napi_get_buffer_info(env, args[0], &data, &length);\n    }\n");
            out.push_str("    size_t count = length / sizeof(double);\n");
            out.push_str("    napi_value result;\n");
            out.push_str("    void* out_data = NULL;\n");
            out.push_str("    napi_create_buffer(env, length, &out_data, &result);\n");
            out.push_str(&format!("    {}((const double*)data, count, (double*)out_data);\n", f.name));
            out.push_str("    return result;\n");
        } else {
            out.push_str(&format!("    uint32_t val = {}();\n", f.name));
            out.push_str("    napi_value result;\n    napi_create_uint32(env, val, &result);\n    return result;\n");
        }
        out.push_str("}\n\n");
    }

    out.push_str("NAPI_MODULE_INIT() {\n");
    for f in fns {
        out.push_str(&format!(
            "    napi_value fn_{};\n    napi_create_function(env, NULL, 0, n_{}, NULL, &fn_{});\n    napi_set_named_property(env, exports, \"{}\", fn_{});\n",
            f.name, f.name, f.name, f.name, f.name
        ));
    }
    out.push_str("    return exports;\n}\n");
    out
}

fn gen_java(fns: &[Function]) -> String {
    let mut out = String::new();
    out.push_str("// Generated by sillstone-idl-gen. DO NOT EDIT.\n");
    out.push_str("package io.github.sillstone;\n\n");
    out.push_str("public final class Generated {\n");
    out.push_str("    static {\n        System.loadLibrary(\"sillstone_ffi\");\n    }\n\n");
    for f in fns {
        if f.name == "sillstone_buffer_checksum" {
            out.push_str("    public static native long sillstone_buffer_checksum(byte[] data, long len);\n\n");
        } else if is_digest_fn(&f.name) {
            out.push_str(&format!("    public static native byte[] {}(byte[] data);\n\n", f.name));
        } else if is_math_dst_fn(&f.name) {
            out.push_str(&format!("    public static native double[] {}(double[] data);\n\n", f.name));
        } else {
            out.push_str(&format!("    public static native int {}();\n\n", f.name));
        }
    }
    out.push_str("}\n");
    out
}

fn main() {
    let args: Vec<String> = env::args().collect();
    let check_mode = args.iter().any(|a| a == "--check");

    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .to_path_buf();

    let idl_path = root.join("abi").join("sillstone.idl");
    let content = fs::read_to_string(&idl_path).expect("failed to read sillstone.idl");
    let fns = parse_idl(&content);

    let targets = vec![
        (root.join("include").join("sillstone.h"), gen_c_header(&fns)),
        (
            root.join("sdk")
                .join("python")
                .join("sillstone")
                .join("_generated.py"),
            gen_python(&fns),
        ),
        (
            root.join("sdk")
                .join("go")
                .join("sillstone")
                .join("generated.go"),
            gen_go(&fns),
        ),
        (
            root.join("sdk").join("node").join("src").join("generated.c"),
            gen_node_napi(&fns),
        ),
        (
            root.join("sdk")
                .join("java")
                .join("src")
                .join("main")
                .join("java")
                .join("io")
                .join("github")
                .join("sillstone")
                .join("Generated.java"),
            gen_java(&fns),
        ),
    ];

    if check_mode {
        for (path, expected) in targets {
            let actual = fs::read_to_string(&path)
                .unwrap_or_else(|_| panic!("failed to read target {:?}", path));
            if actual != expected {
                eprintln!("IDL drift detected in {:?}", path);
                std::process::exit(1);
            }
        }
        println!("IDL definitions in sync across all targets.");
    } else {
        for (path, content) in targets {
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent).unwrap();
            }
            fs::write(&path, content).unwrap();
            println!("Wrote {:?}", path);
        }
    }
}
