"""Build the sillstone Python source distribution from the monorepo.

``sdk/python`` is a subdirectory of the repository, and setuptools only packs
files below the project root. ``python -m build --sdist sdk/python`` therefore
cannot reach ``crates/``: the archive holds the ctypes wrapper and no library,
installs cleanly, and fails on the first native call. ``setup.py`` now refuses
to write such an archive, and this script produces the one that works.

It stages a self-contained tree and builds the sdist from there:

    <stage>/pyproject.toml, setup.py, MANIFEST.in, README.md, LICENSE, NOTICE
    <stage>/sillstone/            (the Python package)
    <stage>/rust/                 (Cargo.toml, crates/, tools/idl-gen/)

``setup.py`` finds ``rust/`` beside itself and runs
``cargo build -p sillstone-ffi --release`` while the wheel is built from the
sdist, so ``pip install --no-binary :all: sillstone`` compiles the cdylib on
the installing machine and a machine without ``cargo`` is told why it cannot.
The workspace has no third-party dependencies, so that build needs no network.

Cargo.lock is gitignored in this repository and is regenerated by the build;
the archive carries source only. Native binaries are deliberately absent: one
binary cannot serve five platforms, and a stale one would be loaded instead of
the freshly compiled library.

Run: python scripts/build-sdist.py [--outdir DIR] [--stage DIR] [--keep]
"""
from __future__ import annotations

import argparse
import importlib.util
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
PY_SDK = ROOT / "sdk" / "python"
PACKAGE = "sillstone"
PROJECT_FILES = ("pyproject.toml", "setup.py", "README.md")
DOC_FILES = ("LICENSE", "NOTICE")
RUST_TREES = ("crates", "tools/idl-gen")
IGNORE = shutil.ignore_patterns("target", "__pycache__", "*.py[cod]", "*.dll", "*.so", "*.dylib", "*.node")

MANIFEST = """\
include LICENSE
include NOTICE
include README.md
include pyproject.toml
include setup.py
graft rust
prune rust/target
global-exclude __pycache__ *.py[cod] *.dll *.so *.dylib *.node
"""


def project_version() -> str:
    """`[project] version` of sdk/python/pyproject.toml, without a tomllib dependency."""
    text = (PY_SDK / "pyproject.toml").read_text(encoding="utf-8")
    in_project = False
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("["):
            in_project = stripped == "[project]"
            continue
        if in_project and stripped.startswith("version ="):
            return stripped.split("=", 1)[1].strip().strip('"')
    raise SystemExit(f"sillstone: no [project] version in {PY_SDK / 'pyproject.toml'}")


def stage_tree(dest: pathlib.Path) -> pathlib.Path:
    """Write the self-contained tree the sdist is built from."""
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    for name in PROJECT_FILES:
        shutil.copy2(PY_SDK / name, dest / name)
    shutil.copytree(PY_SDK / PACKAGE, dest / PACKAGE, ignore=IGNORE)
    for name in DOC_FILES:
        shutil.copy2(ROOT / name, dest / name)
    rust = dest / "rust"
    rust.mkdir()
    shutil.copy2(ROOT / "Cargo.toml", rust / "Cargo.toml")
    for tree in RUST_TREES:
        shutil.copytree(ROOT / tree, rust / tree, ignore=IGNORE)
    (dest / "MANIFEST.in").write_text(MANIFEST, encoding="utf-8")
    return dest


def build_sdist(stage: pathlib.Path, outdir: pathlib.Path, isolation: bool) -> pathlib.Path:
    outdir.mkdir(parents=True, exist_ok=True)
    command = [sys.executable, "-m", "build", "--sdist", "--outdir", str(outdir)]
    if not isolation:
        command.append("--no-isolation")
    command.append(str(stage))
    print(f"sillstone: {' '.join(command)}", flush=True)
    result = subprocess.run(command)
    if result.returncode != 0:
        raise SystemExit(
            "sillstone: the sdist build failed (is the `build` package installed? "
            "`python -m pip install build`)"
        )
    version = project_version()
    tarball = outdir / f"sillstone-{version}.tar.gz"
    if not tarball.is_file():
        produced = sorted(p.name for p in outdir.iterdir())
        raise SystemExit(f"sillstone: expected {tarball}, build produced {', '.join(produced) or 'nothing'}")
    return tarball


def contents_gate(tarball: pathlib.Path) -> None:
    """Reject an archive that would install a package with no native library."""
    spec = importlib.util.spec_from_file_location(
        "check_package_contents", pathlib.Path(__file__).with_name("ci") / "check-package-contents.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    problems = module.check_sdist(tarball)
    for problem in problems:
        print(f"FAIL: {problem}")
    if problems:
        raise SystemExit(f"sillstone: {tarball} is not an installable sdist")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--outdir", default=str(PY_SDK / "dist"), help="where the tarball is written")
    ap.add_argument("--stage", default=str(ROOT / "build" / "sdist"), help="scratch tree for the build")
    ap.add_argument("--keep", action="store_true", help="leave the staged tree in place")
    ap.add_argument("--no-isolation", action="store_true", help="build with the current interpreter's setuptools")
    args = ap.parse_args(argv)
    stage = pathlib.Path(args.stage).resolve()
    outdir = pathlib.Path(args.outdir).resolve()
    try:
        staged = stage_tree(stage)
        tarball = build_sdist(staged, outdir, isolation=not args.no_isolation)
        contents_gate(tarball)
    finally:
        if not args.keep and stage.exists():
            shutil.rmtree(stage)
    size = tarball.stat().st_size
    print(f"ok: {tarball} ({size} bytes) carries the Python package and the Rust workspace")
    return 0


if __name__ == "__main__":
    sys.exit(main())
